#!/usr/bin/env python3
"""Summarise a private Q80T read-only survey without printing identifiers or raw logs.

This is an evidence checklist, never an approval for Home/startup changes.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
PRIVATE_REPORTS = (ROOT / ".local" / "tiz0wn-lab").resolve()
LIMIT = 512 * 1024
PREFS = (
    "db/appfw/home_appid",
    "db/appfw/startup_appid",
    "db/appfw/booting_appid_backup",
    "db/first_screen/type",
    "db/menu/smart_hub/ontvsetting/auto_start",
)
MARKERS = (
    "DANSTV-ROOT-CHANNEL mode=Snapshot",
    "DANSTV-EUID=0",
    "DANSTV-EXIT=0",
    "DANSTV-END-OF-REPORT",
)


def section(lines: list[str], title: str) -> list[str]:
    header = "=== " + title + " ==="
    for i, line in enumerate(lines):
        if line.strip() != header:
            continue
        result = []
        for current in lines[i + 1:]:
            if current.strip().startswith("=== ") and current.strip().endswith(" ==="):
                break
            result.append(current)
        return result
    return []


def assess(text: str) -> dict:
    lines = text.splitlines()
    if len(lines) < 4 or lines[:2] != list(MARKERS[:2]) or lines[-2:] != list(MARKERS[-2:]):
        raise ValueError("Not a complete, successful Q80T snapshot report (format check only)")
    home = section(lines, "Home / startup preference inventory (read-only)")
    keys = {}
    for key in PREFS:
        hits = [line.split(":", 1)[1].strip() for line in home if line.startswith(key + ":")]
        if len(hits) != 1:
            keys[key] = "missing"
        elif hits[0] == "(not readable or absent)" or not hits[0]:
            keys[key] = "unavailable"
        else:
            keys[key] = "reported"
    ctx = section(lines, "Home key context (read-only)")
    if any("No readable app-context database" in line for line in ctx):
        home_key = "unavailable"
    elif any(re.search(r"\bXF86Home\b", line) for line in ctx):
        home_key = "observed"
    elif any("appid" in line and "key" in line for line in ctx):
        home_key = "no row shown"
    else:
        home_key = "unverified"
    # Only the dedicated preference/firmware section is evidence for the
    # target build. A matching string in an unrelated diagnostic is not proof.
    versions = [line.strip() for line in home if line.strip().startswith("Version=")]
    firmware = len(versions) == 1 and bool(
        re.fullmatch(r"Version=T-NKMUABC-2743\.0;?", versions[0])
    )
    prerequisites = section(lines, "Tizen 5.5 service prerequisites (read-only)")

    def signal(label: str) -> str:
        # A shell-probe presence marker is deliberately not a compatibility
        # verdict. Missing/duplicated/unknown output must remain unverified.
        values = [line[len(label) + 2:].strip() for line in prerequisites
                  if line.startswith(label + ": ")]
        if len(values) != 1:
            return "unverified"
        if values[0] == "present":
            return "observed"
        if values[0] == "not observed":
            return "not observed"
        return "unverified"

    smack_values = [line.split(": ", 1)[1].strip() for line in prerequisites
                    if line.startswith("Survey shell SMACK label: ")]
    smack = ("observed" if len(smack_values) == 1
             and smack_values[0] not in ("", "unreadable", "not readable")
             else "unverified")

    return {
        "root_report": "success markers present (not cryptographic proof)", "firmware_marker": "matched" if firmware else "not observed",
        "home_prefs": keys, "home_key_filter": home_key,
        "native_main_operation": "not measured",
        "runtime_prerequisites": {
            "node_executable_in_path": signal("Node executable in PATH"),
            "dotnet_launcher": signal("dotnet launcher executable"),
            "app_data_directory": signal("apps_rw data directory"),
            "survey_shell_smack": smack,
            "web_service_node_version": "not measured",
            "authenticated_broker": "not measured",
        },
        "home_change_authorised": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True,
                        help="Private file generated by root-bridge, under .local/tiz0wn-lab/")
    args = parser.parse_args()
    report = args.report.resolve()
    if PRIVATE_REPORTS not in report.parents or not report.is_file():
        parser.error("Expected a private snapshot report under .local/tiz0wn-lab/")
    if report.stat().st_size > LIMIT:
        parser.error("Report exceeds the reviewed transport limit")
    try:
        result = assess(report.read_text(encoding="utf-8", errors="replace"))
    except ValueError as exc:
        parser.error(str(exc))
    print("Q80T read-only Home compatibility evidence (safe summary, no raw values)")
    print("Root transport:", result["root_report"])
    print("Exact firmware marker:", result["firmware_marker"])
    for key, status in result["home_prefs"].items():
        print(key + ":", status)
    print("XF86Home context:", result["home_key_filter"])
    print("Native Home main-operation:", result["native_main_operation"])
    runtime = result["runtime_prerequisites"]
    print("Node executable in snapshot shell PATH:", runtime["node_executable_in_path"])
    print("dotnet-launcher executable:", runtime["dotnet_launcher"])
    print("App-data directory:", runtime["app_data_directory"])
    print("Snapshot shell SMACK label:", runtime["survey_shell_smack"])
    print("Tizen web-service Node runtime:", runtime["web_service_node_version"])
    print("Authenticated root broker:", runtime["authenticated_broker"])
    print("These shell signals DO NOT establish a working Vetro/DansTV privileged service.")
    print("Home/startup changes authorised: NO")
    print("Next gate: inspect exact original values privately, export/verify off-TV")
    print("backups, and demonstrate an independent recovery route before writes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
