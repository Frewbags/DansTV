#!/usr/bin/env python3
"""Summarise a private Q80T read-only survey without printing identifiers or raw logs.

This is an evidence checklist, never an approval for Home/startup changes.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
PRIVATE_REPORTS = (ROOT / ".local" / "tiz0wn-lab").resolve()
LIMIT = 512 * 1024
PREFS = (
    "db/appfw/home_appid",
    "db/appfw/startup_appid",
    "db/appfw/booting_appid_backup",
    "db/first_screen/type",
    "db/menu/smart_hub/ontvsetting/auto_start",
)
MARKERS = (
    "DANSTV-ROOT-CHANNEL mode=Snapshot",
    "DANSTV-EUID=0",
    "DANSTV-EXIT=0",
    "DANSTV-END-OF-REPORT",
)


def section(lines: list[str], title: str) -> list[str]:
    header = "=== " + title + " ==="
    for i, line in enumerate(lines):
        if line.strip() != header:
            continue
        result = []
        for current in lines[i + 1:]:
            if current.strip().startswith("=== ") and current.strip().endswith(" ==="):
                break
            result.append(current)
        return result
    return []


def assess(text: str) -> dict:
    lines = text.splitlines()
    if len(lines) < 4 or lines[:2] != list(MARKERS[:2]) or lines[-2:] != list(MARKERS[-2:]):
        raise ValueError("Not a complete, successful authenticated Q80T snapshot report")
    home = section(lines, "Home / startup preference inventory (read-only)")
    keys = {}
    for key in PREFS:
        hits = [line.split(":", 1)[1].strip() for line in home if line.startswith(key + ":")]
        if len(hits) != 1:
            keys[key] = "missing"
        elif hits[0] == "(not readable or absent)" or not hits[0]:
            keys[key] = "unavailable"
        else:
            keys[key] = "reported"
    ctx = section(lines, "Home key context (read-only)")
    if any("No readable app-context database" in line for line in ctx):
        home_key = "unavailable"
    elif any(re.search(r"\bXF86Home\b", line) for line in ctx):
        home_key = "observed"
    elif any("appid" in line and "key" in line for line in ctx):
        home_key = "no row shown"
    else:
        home_key = "unverified"
    firmware = any(
        re.search(r"\bVersion=T-NKMUABC-2743\.0(?:;|\b)", line) for line in lines
    )
    return {
        "root_report": "verified marker", "firmware_marker": "matched" if firmware else "not observed",
        "home_prefs": keys, "home_key_filter": home_key,
        "native_main_operation": "not measured",
        "home_change_authorised": False,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True,
                        help="Private file generated by root-bridge, under .local/tiz0wn-lab/")
    args = parser.parse_args()
    report = args.report.resolve()
    if PRIVATE_REPORTS not in report.parents or not report.is_file():
        parser.error("Expected a private snapshot report under .local/tiz0wn-lab/")
    if report.stat().st_size > LIMIT:
        parser.error("Report exceeds the reviewed transport limit")
    try:
        result = assess(report.read_text(encoding="utf-8", errors="replace"))
    except ValueError as exc:
        parser.error(str(exc))
    print("Q80T read-only Home compatibility evidence (safe summary, no raw values)")
    print("Root transport:", result["root_report"])
    print("Exact firmware marker:", result["firmware_marker"])
    for key, status in result["home_prefs"].items():
        print(key + ":", status)
    print("XF86Home context:", result["home_key_filter"])
    print("Native Home main-operation:", result["native_main_operation"])
    print("Home/startup changes authorised: NO")
    print("Next gate: inspect exact original values privately, export/verify off-TV")
    print("backups, and demonstrate an independent recovery route before writes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
